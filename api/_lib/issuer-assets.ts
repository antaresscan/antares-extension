// api/_lib/issuer-assets.ts — Tokens whose structure is an issuer's, by design: stablecoins, tokenized stocks / real-world assets, liquid staking tokens,
// wrapped major assets.
//
// An issuer-backed token is NOT built like a meme coin, and every rule that reads structure reads it wrong:
//   - the issuer holds the mint and the freeze authority (it issues and redeems; it must be able to freeze a sanctioned wallet);
//   - tokenized stocks add a pause, a permanent delegate, accounts that start frozen (regulated securities);
//   - a liquid staking token (JitoSOL, mSOL...) has its stake pool as mint authority and as the holder of most of the supply;
//   - a wrapped major (wrapped BTC, ETH: Coinbase's cbBTC, Portal's WBTC and ETH...) has the bridge or the custodian as mint (and freeze)
//     authority, and the vault of the backing asset as its biggest holder (one wallet at 50 % is the vault);
//   - the issuer / its market makers hold 70-98 % of the supply (top-10 concentration);
//   - the liquidity pool is not what backs the token (redemption is), so "LP not burned" says nothing.
// Measured on the 365 recorded tokens: the 46 tokenized stocks were ALL called RUG (37) or DANGER (9), and so were most stablecoins and
// liquid-staking tokens (the owner's example: "RUG RISK on an Apple stock"). For these tokens the verdict is judged on the MARKET only:
// is there a pool with real liquidity, did the price collapse, can holders sell, did a stablecoin or an LST lose its peg.
//
// WHICH TOKENS: by mint ADDRESS only (issuer-assets.data.ts, generated by scripts/issuer-assets/build.mjs from Jupiter's verified list).
// Never by name or symbol (a look-alike scam has the right name and the wrong address), never by the authority's address (anyone can write
// another party's address as the authority of a mint they create).
//
// THE OWNER'S RULE (2026-10-13): the same for all three. The SAFE of Antares means "no rug signal found", not "no risk" (a meme coin can be
// SAFE too), so an issuer-backed token whose market is healthy is SAFE; what its issuer can do (freeze, pause, reissue) stays visible as an
// information line. What differs is what "the peg" means: $1 for a stablecoin, 1 SOL for an LST, nothing we can read for a stock.
import type { DexScreenerPair, LayerResult, RugKind, SafeBlockedReason, ScanFlag, Verdict } from "./types";
import { LST_MINTS, STABLE_MINTS, TOKENIZED_MINTS, WRAPPED_MINTS } from "./issuer-assets.data";
import { makeFlag } from "./helpers";
import { countVerdictFlags, determineVerdict, rugKindOf } from "./pipeline";

export type IssuerKind = "stable" | "tokenized" | "lst" | "wrapped";

const STABLE = new Set<string>(STABLE_MINTS);
const TOKENIZED = new Set<string>(TOKENIZED_MINTS);
const LST = new Set<string>(LST_MINTS);
const WRAPPED = new Set<string>(WRAPPED_MINTS);

/** Stablecoins of the registry that are not pegged to the dollar: EURC follows the euro (about $1.1), so its distance to $1 says nothing. */
export const NON_USD_STABLE = new Set<string>(["HzwqbKZw8HxMN6bF2yFZNrht3c2iXXzpKcFu7uBEDKtr"]);

/** The kind of issuer-backed token this mint is, or null for any other token. */
export function issuerKindOf(mint: string | null | undefined): IssuerKind | null {
  if (!mint) return null;
  if (STABLE.has(mint)) return "stable";
  if (TOKENIZED.has(mint)) return "tokenized";
  if (LST.has(mint)) return "lst";
  if (WRAPPED.has(mint)) return "wrapped";
  return null;
}

/**
 * The flags that stay what they were for an issuer-backed token: they are about the MARKET (can anybody sell, is there a pool, did the price
 * collapse), not about the structure. Everything else that was critical or warning is shown as information: the user still sees it, it
 * just does not decide the verdict. A positive list on purpose: a flag nobody thought about is not promoted to a verdict.
 */
const MARKET_HEALTH: RegExp[] = [
  /^Very low liquidity/i, /^Low liquidity/i, /^Liquidity < /i, /abandoned pool/i,
  /^Brutal dump/i, /^Significant 24h dump/i, /^Sharp 6h sell-off/i, /^Sharp crash/i, /^Slow rug detected/i, /^Active dump/i,
  /^Progressive dump/i, /^Post-ATH dump/i, /^Collapsed -/i,
  /^Honeypot detected/i, /^Cannot sell all tokens/i, /^Non-transferable token/i, /^Sells blocked/i,
];

/** A stablecoin that moved or sits this far from its $1 peg: a warning from 3 %, critical from 10 %. */
const DEPEG_WARN_PCT = 3;
const DEPEG_CRITICAL_PCT = 10;
/** The distance to $1 is only read on a pool deep enough to mean something (the pool of a stablecoin with $5k in it can say anything). */
const MIN_POOL_LIQUIDITY_FOR_PEG_USD = 25_000;

/** A liquid staking token is worth about 1 SOL and more, rising with the rewards it accrues: under 0.97 SOL a warning, under 0.90 critical. */
export const LST_PEG_WARN = 0.97;
export const LST_PEG_CRITICAL = 0.90;

const SEVERITY_ORDER: Record<string, number> = { critical: 0, warning: 1, info: 2, bonus: 3 };

const WSOL = "So11111111111111111111111111111111111111112";
/** A SOL-quoted pool needs this much liquidity to say what the token is worth in SOL. */
const MIN_SOL_POOL_LIQUIDITY_USD = 5_000;

/**
 * An LST's price in SOL: the `priceNative` of its deepest pool quoted in SOL, among the pools DexScreener lists for the token. null when there
 * is none (the biggest LSTs are mostly quoted in USDC: their price in SOL cannot be read from that), or when it is not a usable number.
 */
export function lstPriceInSol(pairs: DexScreenerPair[] | null | undefined, mint: string): number | null {
  let best: { liq: number; price: number } | null = null;
  for (const p of pairs ?? []) {
    if (p?.baseToken?.address !== mint) continue;
    const q = p.quoteToken;
    if (!(q?.address === WSOL || /^(SOL|WSOL)$/i.test(q?.symbol ?? ""))) continue;
    const liq = p.liquidity?.usd ?? 0;
    const price = Number(p.priceNative);
    if (!(liq >= MIN_SOL_POOL_LIQUIDITY_USD) || !Number.isFinite(price) || price <= 0) continue;
    if (!best || liq > best.liq) best = { liq, price };
  }
  return best ? best.price : null;
}

export interface IssuerJudgement {
  score: number;
  risk: Verdict;
  rugKind: RugKind | null;
  flags: ScanFlag[];
  safeBlocked: boolean;
  safeBlockedReasons: SafeBlockedReason[];
}

export interface IssuerInput {
  kind: IssuerKind;
  mint: string;
  layers: LayerResult[];
  /** The deduplicated flags of the general decision. */
  flags: ScanFlag[];
  sourcesUsedCount: number;
  /** DexScreener's price change of the chosen pool, in percent (null when it did not say). */
  priceChange24hPct: number | null;
  priceChange1hPct: number | null;
  /** The chosen pool's price in USD and its liquidity in USD (null when unknown). */
  priceUsd: number | null;
  poolLiquidityUsd: number | null;
  /** An LST's price in SOL, read from a SOL-quoted pool of the token with real liquidity (null when there is none: the peg cannot be read). */
  priceInSol: number | null;
}

/**
 * The verdict of an issuer-backed token, from its market only. Pure. Returns null when there is no market reading to judge (DexScreener
 * unavailable): the general decision stands then, it is the more cautious one.
 * An LST whose price in SOL cannot be read (no SOL-quoted pool with real liquidity) is judged on its market too, but its peg is NOT verified:
 * a warning says so, so it is CAUTION at best, never SAFE.
 */
export function judgeIssuerAsset(input: IssuerInput): IssuerJudgement | null {
  const { kind, layers } = input;
  if (!layers.some((l) => l.available && l.source === "dexscreener")) return null;

  const kept: ScanFlag[] = [];
  const shown: ScanFlag[] = [];
  for (const f of input.flags) {
    const marketHealth = (f.severity === "critical" || f.severity === "warning") && MARKET_HEALTH.some((re) => re.test(f.label));
    if (marketHealth) kept.push(f);
    else shown.push(f.severity === "critical" || f.severity === "warning" ? { ...f, severity: "info" } : f);
  }

  // The peg: the one structural-looking risk that is a market fact. One flag, the worse reading.
  if (kind === "stable") {
    const moves = [input.priceChange24hPct, input.priceChange1hPct].filter((v): v is number => v !== null && Number.isFinite(v));
    const moved = moves.length ? Math.max(...moves.map(Math.abs)) : 0;
    const readsPrice = input.priceUsd !== null && Number.isFinite(input.priceUsd) && input.priceUsd > 0
      && (input.poolLiquidityUsd ?? 0) >= MIN_POOL_LIQUIDITY_FOR_PEG_USD && !NON_USD_STABLE.has(input.mint);
    // rounded to 6 decimals of a percent: (1 - 0.9) * 100 is 9.999999999999998, and a stablecoin at $0.90 is 10 % off
    const off = readsPrice ? Math.round(Math.abs((input.priceUsd as number) - 1) * 1e8) / 1e6 : 0;
    if (off >= DEPEG_WARN_PCT && off >= moved) {
      kept.push(makeFlag(`Stablecoin trades at $${(input.priceUsd as number).toFixed(4)}, ${off >= 10 ? Math.round(off) : Math.round(off * 10) / 10}% from its $1 peg`, off >= DEPEG_CRITICAL_PCT ? "critical" : "warning", 0));
    } else if (moved >= DEPEG_WARN_PCT) {
      const pct = moved >= 10 ? Math.round(moved) : Math.round(moved * 10) / 10;
      kept.push(makeFlag(`Stablecoin price moved ${pct}% — it may have lost its peg`, moved >= DEPEG_CRITICAL_PCT ? "critical" : "warning", 0));
    }
  } else if (kind === "lst") {
    const r = input.priceInSol;
    if (r === null || !Number.isFinite(r) || r <= 0) {
      kept.push(makeFlag("Liquid staking token — its price in SOL could not be read from a pool with real liquidity, so its peg to SOL is not verified", "warning", 0));
    } else if (r < LST_PEG_WARN) {
      kept.push(makeFlag(`Liquid staking token trades at ${r.toFixed(4)} SOL — it may have lost its peg to SOL`, r < LST_PEG_CRITICAL ? "critical" : "warning", 0));
    }
  }

  const issuerFlag = kind === "stable"
    ? makeFlag("Stablecoin — the issuer holds the mint and freeze authorities and most of the supply by design: they are not read as rug signals", "info", 0)
    : kind === "lst"
      ? makeFlag("Liquid staking token — the stake pool holds the mint authority and most of the supply by design: they are not read as rug signals", "info", 0)
      : kind === "wrapped"
        ? makeFlag("Wrapped asset — the bridge or the custodian holds the mint authority and most of the supply by design: they are not read as rug signals", "info", 0)
        : makeFlag("Tokenized asset — the issuer can freeze, pause or reissue tokens by design: its authorities, the supply it holds and its pause are not read as rug signals", "info", 0);

  const flags = [issuerFlag, ...kept, ...shown].sort((a, b) => (SEVERITY_ORDER[a.severity] ?? 9) - (SEVERITY_ORDER[b.severity] ?? 9));
  const counts = countVerdictFlags(flags);
  // The facts that a rug happened (a drained pool, blocked sells, a collapse) are facts whatever the structure.
  const evidence = layers.some((l) => l.available && (l.rugEvidence?.length ?? 0) > 0);

  let score = Math.round(950 * Math.pow(0.5, counts.critical) * Math.pow(0.85, counts.warning));
  if (evidence) score = Math.min(score, 100);
  const risk = determineVerdict({
    score, forceRug: evidence, safeBlocked: false, safeBlockedReasons: [], sourcesUsedCount: input.sourcesUsedCount,
    warningFlagsCount: counts.warning, criticalFlagsCount: counts.critical, pumpPriceOnlyFlagsCount: counts.pumpPriceOnly,
  });
  return { score, risk, rugKind: rugKindOf(risk, layers), flags, safeBlocked: risk !== "SAFE", safeBlockedReasons: [] };
}
