// api/_lib/issuer-assets.ts — Tokens whose structure is an issuer's, by design: stablecoins and tokenized stocks / real-world assets.
//
// An issuer-backed token is NOT built like a meme coin, and every rule that reads structure reads it wrong:
//   - the issuer holds the mint and the freeze authority (it issues and redeems; it must be able to freeze a sanctioned wallet);
//   - tokenized stocks add a pause, a permanent delegate, accounts that start frozen (regulated securities);
//   - the issuer / its market makers hold 70-98 % of the supply (top-10 concentration);
//   - the liquidity pool is not what backs the token (redemption is), so "LP not burned" says nothing.
// Measured on the 365 recorded tokens: the 46 tokenized stocks were ALL called RUG (37) or DANGER (9), and so were most stablecoins and
// liquid-staking tokens (docs of the audit: "RUG RISK on an Apple stock"). For these tokens the verdict is judged on the MARKET only:
// is there a pool with real liquidity, did the price collapse, can holders sell, did a stablecoin lose its peg.
//
// WHICH TOKENS: by mint ADDRESS only (issuer-assets.data.ts, generated by scripts/issuer-assets/build.mjs from Jupiter's verified list).
// Never by name or symbol: a look-alike scam has the right name and the wrong address, and stays judged as any other token.
//
// THE OWNER'S RULE (2026-10-13): the same for both. The SAFE of Antares means "no rug signal found", not "no risk" (a meme coin can be SAFE
// too), so an issuer-backed token whose market is healthy is SAFE; what its issuer can do (freeze, pause, reissue) stays visible as an
// information line. Refusing SAFE to a stock for a "residual risk" would be inconsistent with a SAFE meme coin, and with a SAFE stablecoin
// whose issuer holds the very same powers. (The first version of this rule made stocks CAUTION at the very least; the owner reversed it.)
import type { LayerResult, RugKind, SafeBlockedReason, ScanFlag, Verdict } from "./types";
import { STABLE_MINTS, TOKENIZED_MINTS } from "./issuer-assets.data";
import { makeFlag } from "./helpers";
import { countVerdictFlags, determineVerdict, rugKindOf } from "./pipeline";

export type IssuerKind = "stable" | "tokenized";

const STABLE = new Set<string>(STABLE_MINTS);
const TOKENIZED = new Set<string>(TOKENIZED_MINTS);

/** The kind of issuer-backed token this mint is, or null for any other token. */
export function issuerKindOf(mint: string | null | undefined): IssuerKind | null {
  if (!mint) return null;
  if (STABLE.has(mint)) return "stable";
  if (TOKENIZED.has(mint)) return "tokenized";
  return null;
}

/**
 * The flags that stay what they were for an issuer-backed token: they are about the MARKET (can anybody sell, is there a pool, did the price
 * collapse), not about the structure. Everything else that was critical or warning is shown as information: the user still sees it, it
 * just does not decide the verdict. A positive list on purpose: a flag nobody thought about is not promoted to a verdict.
 */
const MARKET_HEALTH: RegExp[] = [
  /^Very low liquidity/i, /^Low liquidity/i, /^Liquidity < /i, /abandoned pool/i,
  /^Brutal dump/i, /^Significant 24h dump/i, /^Sharp 6h sell-off/i, /^Sharp crash/i, /^Slow rug detected/i, /^Active dump/i,
  /^Progressive dump/i, /^Post-ATH dump/i, /^Collapsed -/i,
  /^Honeypot detected/i, /^Cannot sell all tokens/i, /^Non-transferable token/i, /^Sells blocked/i,
];

/** A stablecoin that moved this much in an hour or a day is losing its peg: a warning from 3 %, critical from 10 %. */
const DEPEG_WARN_PCT = 3;
const DEPEG_CRITICAL_PCT = 10;

const SEVERITY_ORDER: Record<string, number> = { critical: 0, warning: 1, info: 2, bonus: 3 };

export interface IssuerJudgement {
  score: number;
  risk: Verdict;
  rugKind: RugKind | null;
  flags: ScanFlag[];
  safeBlocked: boolean;
  safeBlockedReasons: SafeBlockedReason[];
}

export interface IssuerInput {
  kind: IssuerKind;
  layers: LayerResult[];
  /** The deduplicated flags of the general decision. */
  flags: ScanFlag[];
  sourcesUsedCount: number;
  /** DexScreener's price change of the chosen pool, in percent (null when it did not say). */
  priceChange24hPct: number | null;
  priceChange1hPct: number | null;
}

/**
 * The verdict of an issuer-backed token, from its market only. Pure. Returns null when there is no market reading to judge (DexScreener
 * unavailable): the general decision stands then, it is the more cautious one.
 */
export function judgeIssuerAsset(input: IssuerInput): IssuerJudgement | null {
  const { kind, layers } = input;
  if (!layers.some((l) => l.available && l.source === "dexscreener")) return null;

  const kept: ScanFlag[] = [];
  const shown: ScanFlag[] = [];
  for (const f of input.flags) {
    const marketHealth = (f.severity === "critical" || f.severity === "warning") && MARKET_HEALTH.some((re) => re.test(f.label));
    if (marketHealth) kept.push(f);
    else shown.push(f.severity === "critical" || f.severity === "warning" ? { ...f, severity: "info" } : f);
  }

  // A stablecoin that loses its peg is the one structural-looking risk that is a market fact.
  if (kind === "stable") {
    const moves = [input.priceChange24hPct, input.priceChange1hPct].filter((v): v is number => v !== null && Number.isFinite(v));
    const worst = moves.length ? Math.max(...moves.map(Math.abs)) : 0;
    if (worst >= DEPEG_WARN_PCT) {
      const pct = worst >= 10 ? Math.round(worst) : Math.round(worst * 10) / 10;
      kept.push(makeFlag(`Stablecoin price moved ${pct}% — it may have lost its peg`, worst >= DEPEG_CRITICAL_PCT ? "critical" : "warning", 0));
    }
  }

  const issuerFlag = kind === "stable"
    ? makeFlag("Stablecoin — the issuer holds the mint and freeze authorities and most of the supply by design: they are not read as rug signals", "info", 0)
    : makeFlag("Tokenized asset — the issuer can freeze, pause or reissue tokens by design: its authorities, the supply it holds and its pause are not read as rug signals", "info", 0);

  const flags = [issuerFlag, ...kept, ...shown].sort((a, b) => (SEVERITY_ORDER[a.severity] ?? 9) - (SEVERITY_ORDER[b.severity] ?? 9));
  const counts = countVerdictFlags(flags);
  // The facts that a rug happened (a drained pool, blocked sells, a collapse) are facts whatever the structure.
  const evidence = layers.some((l) => l.available && (l.rugEvidence?.length ?? 0) > 0);

  let score = Math.round(950 * Math.pow(0.5, counts.critical) * Math.pow(0.85, counts.warning));
  if (evidence) score = Math.min(score, 100);
  const risk = determineVerdict({
    score, forceRug: evidence, safeBlocked: false, safeBlockedReasons: [], sourcesUsedCount: input.sourcesUsedCount,
    warningFlagsCount: counts.warning, criticalFlagsCount: counts.critical, pumpPriceOnlyFlagsCount: counts.pumpPriceOnly,
  });
  return { score, risk, rugKind: rugKindOf(risk, layers), flags, safeBlocked: risk !== "SAFE", safeBlockedReasons: [] };
}
